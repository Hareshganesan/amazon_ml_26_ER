"""Automated French analysis for the Amazon ML Challenge 2026 entity-resolution task.

Runs every data-dependent step of the France brief and writes the deliverable notes:

  1. top-N token frequencies in business_name / business_address, per source (S1, S2, S3)
  2. FR_LEGAL / FR_ADDR from french_rules.py pruned to entries actually observed -> fr_rules_observed.py
  3. audit of 30 French S1 entities WITH predicted matches, each pair pre-labelled correct/wrong/unsure
  4. 20 French S1 entities with NO prediction, each with its nearest unclaimed S2/S3 record
  5. notes_french.md assembling the numbers and examples

Uses only the provided dataset -- no external data, no lookups.

Kaggle usage (CPU is enough; upload french_rules.py and features.py alongside)::

    !python fr_analysis.py --pred /kaggle/input/<your-upload>/v1_matching_results.tsv \
                           --out /kaggle/working/fr_out

Local dry run on the predictions file alone (skips everything needing the test rows)::

    python fr_analysis.py --pred v1_matching_results.tsv --out fr_out --pred_only
"""
import argparse
import os
import re
from collections import Counter
from glob import glob

import pandas as pd

from french_rules import (
    FR_ADDR, FR_ADDR_DROP, FR_LEGAL, ascii_fold, fr_core_name, is_domain_name, normalise_fr_addr,
    normalise_fr_name, squash_name,
)

_non_word = re.compile(r"[^\w]+")
COLS = ["entity_id", "business_name", "business_address", "country"]


def find_dataset(explicit=None):
    """Locate the dataset root containing train/ and test/, on Kaggle or locally."""
    if explicit:
        return explicit
    for pattern in ("/kaggle/input/**/dataset/test", "/kaggle/input/**/test"):
        hits = glob(pattern, recursive=True)
        if hits:
            return os.path.dirname(hits[0])
    raise SystemExit("dataset not found; pass --data <path containing test/>")


def read_french(path, chunksize=500_000):
    """Stream one test TSV and return only its France rows, with normalised columns added."""
    parts = []
    for chunk in pd.read_csv(path, sep="\t", dtype=str, keep_default_na=False,
                             usecols=COLS, chunksize=chunksize):
        parts.append(chunk[chunk["country"] == "France"])
    df = pd.concat(parts, ignore_index=True)
    df["fr_name"] = df["business_name"].map(normalise_fr_name)
    df["fr_core"] = df["business_name"].map(fr_core_name)
    df["fr_addr"] = df["business_address"].map(normalise_fr_addr)
    df["postcode"] = df["business_address"].str.extract(r"\b(\d{5})\b", expand=False).fillna("")
    return df


def raw_tokens(value):
    """Fold accents and split on non-word characters, WITHOUT expanding abbreviations.

    This is ``norm_name`` exactly; it deliberately differs from ``norm_addr``, whose ADDR
    substitution would rewrite ``av`` -> ``avenue`` and hide the very abbreviations we are
    counting in order to discover the French rules.
    """
    return [t for t in _non_word.split(ascii_fold(value)) if t]


def top_tokens(series, n=300):
    """Most common raw tokens of a text column."""
    counter = Counter()
    for value in series:
        counter.update(raw_tokens(value))
    return pd.DataFrame(counter.most_common(n), columns=["token", "count"])


def write_token_tables(sources, out, n=300):
    """Write top-N token tables per source and field; return {(src, field): DataFrame}."""
    tables = {}
    for src, df in sources.items():
        for field, col in (("name", "business_name"), ("addr", "business_address")):
            table = top_tokens(df[col], n)
            table.to_csv(os.path.join(out, "tokens_%s_%s.tsv" % (src, field)), sep="\t", index=False)
            tables[(src, field)] = table
    return tables


def prune_rules(sources, out, min_count=5):
    """Keep only rule entries whose key really occurs in the French rows; write fr_rules_observed.py."""
    name_counts, addr_counts = Counter(), Counter()
    for df in sources.values():
        for value in df["business_name"]:
            name_counts.update(raw_tokens(value))
        for value in df["business_address"]:
            addr_counts.update(raw_tokens(value))

    legal = {t: name_counts[t] for t in sorted(FR_LEGAL) if name_counts[t] >= min_count}
    addr = {k: addr_counts[k] for k in sorted(FR_ADDR) if addr_counts[k] >= min_count}
    drop = {t: addr_counts[t] for t in sorted(FR_ADDR_DROP) if addr_counts[t] >= min_count}

    path = os.path.join(out, "fr_rules_observed.py")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write('"""FR_LEGAL / FR_ADDR pruned to entries observed in the French test rows.\n\n')
        fh.write("Generated by fr_analysis.py; every entry occurs at least %d times.\n" % min_count)
        fh.write('Counts are shown as trailing comments.\n"""\n\n')
        fh.write("FR_LEGAL = {\n")
        for token, count in sorted(legal.items(), key=lambda kv: -kv[1]):
            fh.write('    "%s",  # %d\n' % (token, count))
        fh.write("}\n\nFR_ADDR = {\n")
        for key, count in sorted(addr.items(), key=lambda kv: -kv[1]):
            fh.write('    "%s": "%s",  # %d\n' % (key, FR_ADDR[key], count))
        fh.write("}\n\nFR_ADDR_DROP = {\n")
        for token, count in sorted(drop.items(), key=lambda kv: -kv[1]):
            fh.write('    "%s",  # %d\n' % (token, count))
        fh.write("}\n")
    dropped = (sorted(set(FR_LEGAL) - set(legal)), sorted(set(FR_ADDR) - set(addr)))
    return legal, addr, drop, dropped


try:  # optional on a bare machine, always present on Kaggle
    from rapidfuzz import fuzz
except ImportError:
    fuzz = None


def _jacc(x, y):
    """Token Jaccard on a 0-100 scale; -1 when either side is empty (same sentinel as features.py)."""
    sx, sy = set(x.split()), set(y.split())
    if not sx or not sy:
        return -1.0
    return 100.0 * len(sx & sy) / len(sx | sy)


def admin_components(sources, out, min_count=200):
    """Derive the city / region vocabulary from the data itself.

    French test addresses carry no postcode; they are comma-separated components in arbitrary
    order, e.g. "478 Grande Rue du Petit Courgain, Calais, Hauts-de-France". A street line is
    near-unique, an admin area recurs across thousands of businesses -- so components above a
    frequency floor are the cities and regions. Nothing external is consulted.
    """
    counter = Counter()
    for df in sources.values():
        for value in df["business_address"]:
            for part in value.split(","):
                key = " ".join(raw_tokens(part))
                if key:
                    counter[key] += 1
    admin = {k: v for k, v in counter.items() if v >= min_count}
    header = (
        '"""City / region address components derived from the French test rows.\n\n'
        "Components occurring at least %d times. They appear in every French address and differ\n"
        "systematically between sources (S1 tends to carry the region, S2/S3 the departement),\n"
        'so they add matching noise rather than signal.\n"""\n\nFR_ADMIN = {\n' % min_count
    )
    with open(os.path.join(out, "fr_admin.py"), "w", encoding="utf-8") as fh:
        fh.write(header)
        for key, count in sorted(admin.items(), key=lambda kv: -kv[1]):
            fh.write('    "%s",  # %d\n' % (key, count))
        fh.write("}\n")
    return admin


def admin_key(addr, admin):
    """The most specific admin component of an address (the rarest one present), or ''."""
    present = [(admin[k], k) for k in (" ".join(raw_tokens(p)) for p in addr.split(",")) if k in admin]
    return min(present)[1] if present else ""


def _scores(a, b):
    """Name and address similarity of two rows; address is -1 when either address is empty."""
    if not a["fr_addr"] or not b["fr_addr"]:
        addr_score = -1.0
    elif fuzz is not None:
        addr_score = fuzz.token_set_ratio(a["fr_addr"], b["fr_addr"])
    else:
        addr_score = _jacc(a["fr_addr"], b["fr_addr"])
    if fuzz is not None:
        return fuzz.token_sort_ratio(a["fr_core"], b["fr_core"]), addr_score
    return _jacc(a["fr_core"], b["fr_core"]), addr_score


def prelabel(name_score, addr_score, postcode_eq, squash_eq=0):
    """Heuristic correct/wrong/unsure pre-label for a predicted pair (a human confirms it).

    Address and postcode use -1 for "unknown" (missing on one side); an unknown never counts as
    evidence against a pair, so a missing address can only ever yield "unsure". squash_eq covers
    website records, whose concatenated name scores 0 against the spelled-out name.
    """
    if squash_eq == 1:
        return "correct"
    if name_score >= 90 or (name_score >= 75 and postcode_eq == 1):
        return "correct"
    if name_score < 55 and postcode_eq == 0 and 0 <= addr_score < 60:
        return "wrong"
    return "unsure"


def audit_matched(pred, s1, others, out, n=30, seed=0):
    """Audit n French S1 entities that have predictions; one output row per predicted pair."""
    fr_ids = set(s1["entity_id"])
    have = pred[pred["source1_entity_id"].isin(fr_ids) & (pred["matched_entity_ids"] != "")]
    sample = have.sample(min(n, len(have)), random_state=seed)
    s1_by_id = s1.set_index("entity_id")
    other_by_id = others.set_index("entity_id")

    rows = []
    for _, r in sample.iterrows():
        a = s1_by_id.loc[r["source1_entity_id"]]
        for mid in r["matched_entity_ids"].split(","):
            mid = mid.strip()
            if mid not in other_by_id.index:
                rows.append({"s1_id": a.name, "s1_name": a["business_name"], "match_id": mid,
                             "match_name": "<NOT IN FRENCH ROWS>", "verdict_auto": "wrong",
                             "verdict_human": ""})
                continue
            b = other_by_id.loc[mid]
            name_score, addr_score = _scores(a, b)
            pc = -1 if not a["postcode"] or not b["postcode"] else int(a["postcode"] == b["postcode"])
            sa, sb = squash_name(a["business_name"]), squash_name(b["business_name"])
            squash_eq = int(bool(sa) and bool(sb) and (sa == sb or sa in sb or sb in sa))
            rows.append({
                "domain": int(is_domain_name(b["business_name"])), "squash_eq": squash_eq,
                "s1_id": a.name, "s1_name": a["business_name"], "s1_addr": a["business_address"],
                "match_id": mid, "match_name": b["business_name"], "match_addr": b["business_address"],
                "name_score": round(float(name_score), 1), "addr_score": round(float(addr_score), 1),
                "postcode_eq": pc,
                "verdict_auto": prelabel(name_score, addr_score, pc, squash_eq),
                "verdict_human": "",
            })
    table = pd.DataFrame(rows)
    table.to_csv(os.path.join(out, "audit_matched.tsv"), sep="\t", index=False)
    return table


def audit_unmatched(pred, s1, others, admin, out, n=20, seed=0, top=3):
    """For n French S1 entities with no prediction, show the nearest same-departement S2/S3 records."""
    from sklearn.feature_extraction.text import TfidfVectorizer

    fr_ids = set(s1["entity_id"])
    empty = pred[pred["source1_entity_id"].isin(fr_ids) & (pred["matched_entity_ids"] == "")]
    sample = empty.sample(min(n, len(empty)), random_state=seed)
    s1_by_id = s1.set_index("entity_id")

    claimed = set()
    for ids in pred["matched_entity_ids"]:
        if ids:
            claimed.update(i.strip() for i in ids.split(","))

    others = others.copy()
    others["admin"] = others["business_address"].map(lambda v: admin_key(v, admin))
    by_admin = {d: g for d, g in others.groupby("admin") if d}

    rows = []
    for _, r in sample.iterrows():
        a = s1_by_id.loc[r["source1_entity_id"]]
        pool = by_admin.get(admin_key(a["business_address"], admin))
        if pool is None or pool.empty:
            rows.append({"s1_id": a.name, "s1_name": a["business_name"],
                         "s1_addr": a["business_address"], "best_id": "",
                         "note": "no admin-area pool for this address"})
            continue
        text = (pool["fr_core"] + " " + pool["fr_addr"]).tolist()
        vec = TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 3), min_df=1)
        matrix = vec.fit_transform(text)
        query = vec.transform([a["fr_core"] + " " + a["fr_addr"]])
        sims = (matrix @ query.T).toarray().ravel()
        for rank in sims.argsort()[::-1][:top]:
            b = pool.iloc[rank]
            rows.append({
                "s1_id": a.name, "s1_name": a["business_name"], "s1_addr": a["business_address"],
                "best_id": b["entity_id"], "best_name": b["business_name"],
                "best_addr": b["business_address"], "cosine": round(float(sims[rank]), 3),
                "already_claimed": int(b["entity_id"] in claimed),
                "looks_like_match": "", "note": "",
            })
    table = pd.DataFrame(rows)
    table.to_csv(os.path.join(out, "audit_unmatched.tsv"), sep="\t", index=False)
    return table


def write_notes(out, sources, tables, pruned, matched, unmatched):
    """Assemble notes_french.md from the generated tables (numbers only, nothing invented)."""
    legal, addr, drop, dropped = pruned
    counts = matched["verdict_auto"].value_counts().to_dict() if len(matched) else {}
    n_entities = matched["s1_id"].nunique() if len(matched) else 0
    lines = [
        "# French rows: tokens, rules and prediction audit", "",
        "Generated by `fr_analysis.py` from the French rows of `test_source{1,2,3}.tsv` and",
        "`v1_matching_results.tsv`. No external data was used.", "",
        "## 1. Coverage", "",
        "| Source | French rows |", "|---|---|",
    ]
    lines += ["| %s | %s |" % (src, format(len(df), ",")) for src, df in sources.items()]
    lines += ["", "## 2. Most frequent tokens", "",
              "Full top-300 lists per source and field are in `tokens_<src>_<field>.tsv`. Top 15:", ""]
    for (src, field), table in tables.items():
        head = ", ".join("%s (%d)" % (t, c) for t, c in table.head(15).itertuples(index=False))
        lines.append("- **%s %s**: %s" % (src, field, head))
    lines += ["", "## 3. Rules kept after pruning", "",
              "- `FR_LEGAL`: %d of %d candidates observed; dropped as unseen: %s"
              % (len(legal), len(FR_LEGAL), ", ".join(dropped[0]) or "none"),
              "- `FR_ADDR`: %d of %d candidates observed; dropped as unseen: %s"
              % (len(addr), len(FR_ADDR), ", ".join(dropped[1]) or "none"),
              "- `FR_ADDR_DROP`: %d observed" % len(drop),
              "", "Pruned dictionaries ready to ship: `fr_rules_observed.py`.", "",
              "## 4. Audit of French S1 entities with matches", "",
              "%d predicted pairs over %d entities." % (len(matched), n_entities),
              "Automatic pre-labels (confirm by hand in the `verdict_human` column of",
              "`audit_matched.tsv`; only the confirmed counts go into the report):", ""]
    lines += ["- %s: %s" % (k, v) for k, v in counts.items()]
    lines += ["", "## 5. French S1 entities with no prediction", "",
              "`audit_unmatched.tsv` lists the 3 nearest same-departement S2/S3 records per entity,",
              "with `already_claimed` marking records another S1 entity already took.",
              "%d rows over %d entities." % (len(unmatched),
                                             unmatched["s1_id"].nunique() if len(unmatched) else 0),
              "", "## 6. Error patterns", "", "_(fill in after reviewing the two audit files)_", ""]
    with open(os.path.join(out, "notes_french.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    """French analysis: token frequencies, rule pruning (-> fr_rules_observed.py), FR_ADMIN vocabulary (-> fr_admin.py) and the match audit."""
    ap = argparse.ArgumentParser(description="French rules + prediction audit")
    ap.add_argument("--data", help="dataset root containing test/ (auto-detected on Kaggle)")
    ap.add_argument("--pred", default="v1_matching_results.tsv", help="v1 predictions TSV")
    ap.add_argument("--out", default="fr_out", help="output directory")
    ap.add_argument("--top", type=int, default=300, help="tokens per list")
    ap.add_argument("--min_count", type=int, default=5, help="min occurrences to keep a rule")
    ap.add_argument("--n_matched", type=int, default=30)
    ap.add_argument("--n_unmatched", type=int, default=20)
    ap.add_argument("--admin_min", type=int, default=200,
                    help="min occurrences for an address component to count as a city/region")
    ap.add_argument("--pred_only", action="store_true", help="only summarise the predictions file")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    pred = pd.read_csv(args.pred, sep="\t", dtype=str, keep_default_na=False)
    empty_share = (pred["matched_entity_ids"] == "").mean()
    print("predictions: %s rows, %.1f%% with no match" % (format(len(pred), ","), 100 * empty_share))
    if args.pred_only:
        return

    data = find_dataset(args.data)
    sources = {}
    for i in (1, 2, 3):
        sources["S%d" % i] = read_french(os.path.join(data, "test", "test_source%d.tsv" % i))
        print("S%d: %s French rows" % (i, format(len(sources["S%d" % i]), ",")))

    tables = write_token_tables(sources, args.out, args.top)
    pruned = prune_rules(sources, args.out, args.min_count)
    print("rules kept: FR_LEGAL %d, FR_ADDR %d, FR_ADDR_DROP %d"
          % (len(pruned[0]), len(pruned[1]), len(pruned[2])))

    others = pd.concat([sources["S2"], sources["S3"]], ignore_index=True)
    admin = admin_components(sources, args.out, args.admin_min)
    print("admin components derived: %d" % len(admin))
    matched = audit_matched(pred, sources["S1"], others, args.out, args.n_matched)
    unmatched = audit_unmatched(pred, sources["S1"], others, admin, args.out, args.n_unmatched)
    write_notes(args.out, sources, tables, pruned, matched, unmatched)
    print("wrote %s/notes_french.md and the audit tables" % args.out)


if __name__ == "__main__":
    main()
